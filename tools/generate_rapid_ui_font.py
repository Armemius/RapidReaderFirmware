"""Generate the embedded RapidReader UI font (requires freetype-py and fonttools)."""

from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "localization"))
from u8g2_font import encode_outline
from fontTools.ttLib import TTFont


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = ROOT / "third_party/rapid-mono/RapidMono-Regular.ttf"
    cmap = TTFont(source).getBestCmap()
    requested = set(range(32, 384)) | set(range(0x400, 0x500)) | set(range(0x2010, 0x2027)) | {0x2116, 0x20ac}
    codepoints = requested & cmap.keys()
    assert (set(range(0x410, 0x450)) | {0x401, 0x451}) <= codepoints
    data = encode_outline(source, codepoints, 13)
    lines = ["#pragma once", "", "// Generated by tools/generate_rapid_ui_font.py. SIL OFL 1.1; derived from IBM Plex Mono.",
             "#include <Arduino.h>", "", "namespace ui::fonts {",
             f"inline constexpr uint8_t kRapidUiCellWidth = {data[9]};",
             f"inline constexpr uint8_t kRapidUiHeight = {data[10]};",
             "inline constexpr uint8_t RapidMono13[] PROGMEM = {"]
    for offset in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 20]) + ",")
    lines += ["};", "} // namespace ui::fonts", ""]
    output = ROOT / "src/fonts/RapidMono13.h"
    expected = "\n".join(lines)
    current = output.read_text() if output.exists() else ""
    if args.check and current != expected:
        raise SystemExit(f"Out of date: {output}")
    if not args.check and current != expected:
        output.write_text(expected)
    print(f"Generated {output}: {len(data)} bytes, cell {data[9]}x{data[10]}")


if __name__ == "__main__":
    main()
